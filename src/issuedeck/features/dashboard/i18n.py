def language_from_request(request: Request) -> str:
    raw = request.cookies.get(DASHBOARD_LANG_COOKIE) or DEFAULT_LANG
    return raw if raw in SUPPORTED_LANGS else DEFAULT_LANG


def make_translator(lang: str) -> Callable[..., str]:
    messages = _MESSAGES.get(lang, _MESSAGES[DEFAULT_LANG])
    fallback = _MESSAGES[DEFAULT_LANG]

    def _t(key: str, **kwargs: object) -> str:
        message = messages.get(key, fallback.get(key, key))
        if kwargs:
            return message.format(**kwargs)
        return message

    return _t
